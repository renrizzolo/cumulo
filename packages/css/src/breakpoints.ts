/**
 * CSS length units supported as shorthand min-width media query breakpoint values.
 */
export type BreakpointLengthUnit = 'px' | 'rem' | 'em' | 'ch' | 'vw' | 'vi';

/**
 * Valid breakpoint or container condition query string.
 *
 * Accepts:
 * - Full media queries: `'@media (min-width: 768px)'`
 * - Container size or style queries: `'@container (min-width: 400px)'`,
 *   `'@container card (min-width: 600px)'`, `'@container style(--theme-viewport-md: var(--theme-breakpoint-md))'`
 * - Parenthesized media conditions: `'(min-width: 768px)'`
 * - Shorthand length values: `'768px'`, `'48rem'`, `'48em'` (normalized to `@media (min-width: ...)`)
 */
export type BreakpointQuery =
  | `@media ${string}`
  | `@container ${string}`
  | `(${string})`
  | `${number}${BreakpointLengthUnit}`;

/**
 * Map of named responsive conditions (viewport breakpoints or custom container queries).
 * Insertion order defines cascade priority (earlier keys have lower priority than later keys).
 */
export type BreakpointMap = Readonly<Record<string, BreakpointQuery>>;

/**
 * Declaration-merging interface for custom application breakpoints.
 *
 * Augment this interface (automatically generated by `@cumulo/core` CLI when using custom
 * theme breakpoints, or manually via `declare module '@cumulo/css'`) to override the
 * default breakpoint keys across all `recipe()` definitions.
 */
// eslint-disable-next-line @typescript-eslint/no-empty-object-type
export interface CustomBreakpoints {}

/**
 * Default breakpoint keys matching `@cumulo/core` Container sizes (`theme.css`).
 */
export type DefaultBreakpointKey = 'sm' | 'md' | 'lg' | 'xl' | '2xl';

/**
 * Active global breakpoint keys used by `recipe()` when local `breakpoints` are not provided.
 */
export type RegisteredBreakpointKey = keyof CustomBreakpoints extends never
  ? DefaultBreakpointKey
  : Extract<keyof CustomBreakpoints, string>;

/**
 * Canonical default viewport breakpoints matching `@cumulo/core/theme.css`.
 */
export const DEFAULT_BREAKPOINTS = {
  sm: '@media (min-width: 640px)',
  md: '@media (min-width: 768px)',
  lg: '@media (min-width: 1024px)',
  xl: '@media (min-width: 1280px)',
  '2xl': '@media (min-width: 1440px)',
} as const satisfies BreakpointMap;

/**
 * Normalizes a {@link BreakpointQuery} into a canonical CSS `@media` or `@container` at-rule header.
 */
export function normalizeBreakpointQuery(raw: string): `@media ${string}` | `@container ${string}` {
  const trimmed = raw.trim();
  if (trimmed.startsWith('@media ')) {
    return `@media ${trimmed.slice('@media '.length).trim()}`;
  }
  if (trimmed.startsWith('@container ')) {
    return `@container ${trimmed.slice('@container '.length).trim()}`;
  }
  if (trimmed.startsWith('(')) {
    return `@media ${trimmed}`;
  }
  return `@media (min-width: ${trimmed})`;
}

interface BreakpointRegistryStore {
  breakpoints: Record<string, BreakpointQuery>;
}

const GLOBAL_BREAKPOINTS_KEY = Symbol.for('__CUMULO_BREAKPOINTS__');

function isBreakpointQueryRecord(value: unknown): value is Record<string, BreakpointQuery> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isRegistryStore(value: unknown): value is BreakpointRegistryStore {
  return (
    typeof value === 'object' &&
    value !== null &&
    'breakpoints' in value &&
    isBreakpointQueryRecord(value.breakpoints)
  );
}

function getRegistryStore(): BreakpointRegistryStore {
  const existing: unknown = Reflect.get(globalThis, GLOBAL_BREAKPOINTS_KEY);
  if (isRegistryStore(existing)) {
    return existing;
  }
  const store: BreakpointRegistryStore = {
    breakpoints: { ...DEFAULT_BREAKPOINTS },
  };
  Reflect.set(globalThis, GLOBAL_BREAKPOINTS_KEY, store);
  return store;
}

/**
 * Registers the active global breakpoint map used by `recipe()` calls that omit local `breakpoints`.
 * Typically called by `@cumulo/unplugin` / `@cumulo/parcel-plugin` during extraction or manually at startup.
 */
export function configureBreakpoints(breakpoints: BreakpointMap): void {
  const normalized: Record<string, BreakpointQuery> = {};
  for (const [key, query] of Object.entries(breakpoints)) {
    normalized[key] = normalizeBreakpointQuery(query);
  }
  getRegistryStore().breakpoints = normalized;
}

/**
 * Returns the currently registered global breakpoints in declaration order.
 */
export function getBreakpoints(): BreakpointMap {
  return getRegistryStore().breakpoints;
}

/**
 * Resets global breakpoints back to {@link DEFAULT_BREAKPOINTS}.
 */
export function resetBreakpoints(): void {
  getRegistryStore().breakpoints = { ...DEFAULT_BREAKPOINTS };
}

/**
 * Type-safe helper for defining a breakpoint or custom container query map.
 * Preserves literal keys and query strings for full autocomplete in `recipe()`.
 */
export function defineBreakpoints<const T extends BreakpointMap>(breakpoints: T): T {
  return breakpoints;
}
